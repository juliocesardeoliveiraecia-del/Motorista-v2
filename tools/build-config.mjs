import fs from 'node:fs';
import path from 'node:path';

// Preview builds deliberately receive no production Supabase credentials.
const root = process.cwd();
const version = JSON.parse(fs.readFileSync(path.join(root, 'version.json'), 'utf8')).version;
const vercelEnv = process.env.VERCEL_ENV || 'preview';
const environment = vercelEnv === 'production' ? 'production' : 'preview';
const url = String(process.env.SUPABASE_URL || '').trim();
const publishableKey = String(process.env.SUPABASE_ANON_KEY || process.env.SUPABASE_PUBLISHABLE_KEY || '').trim();

if (environment === 'production' && (!url || !publishableKey)) {
  throw new Error('Production build blocked: SUPABASE_URL and SUPABASE_ANON_KEY are required.');
}
if (url && !/^https:\/\/[a-z0-9-]+\.supabase\.co$/i.test(url)) {
  throw new Error('Invalid SUPABASE_URL: expected the HTTPS Supabase project URL.');
}
if (publishableKey && !publishableKey.startsWith('sb_publishable_')) {
  throw new Error('Invalid public client key: expected a Supabase publishable key.');
}

const enabled = Boolean(url && publishableKey);
const output = `/* Generated by tools/build-config.mjs. Public client configuration only. */
window.DOCTOR_PRODUCTION_CONFIG = Object.freeze({
  version: '${version}',
  environment: '${environment}',
  integrations: {
    supabase: { enabled: ${enabled}, url: ${JSON.stringify(url)}, publishableKey: ${JSON.stringify(publishableKey)} },
    payments: { enabled: false, provider: 'doctor-platform', checkoutUrl: '' },
    platform: { bridgeEnabled: true }
  }
});
`;
fs.writeFileSync(path.join(root, 'production-config.js'), output);
console.log('Doctor Core runtime config generated:', environment, enabled ? 'Supabase connected' : 'Supabase disabled in preview');
